Console.WriteLine("for loop:");
for (int i = 1; i <= 5; i++)
{
    Console.WriteLine(i);
}

Console.WriteLine("while loop:");
int count = 10;
while (count <= 5)
{
    Console.WriteLine(count);
    count++;
}

Console.WriteLine("do-while loop:");
int number = 10;
do
{
    Console.WriteLine(number);
    number++;
}
while (number <= 5);
